/**
 * P6-20 (ADR-159): write `packages/contracts/src/i18n-keys.gen.ts` — the
 * typed message keys and their params — from the reference pack
 * (`packages/contracts/locales/en/*.json`). `--check`: exit 1 when the
 * committed file differs (tests/i18n.test.ts runs the same check).
 *
 *   npm run gen:i18n            # after adding or renaming keys
 *   npm run gen:i18n -- --check
 *
 * Sorted by key, one line each, so packages that add keys to different
 * areas in parallel touch different lines (a conflict: run it again).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { BUILTIN_PARAMS, FALLBACK_LANG, paramsOf } from "../packages/contracts/src/i18n.ts";
import { readPackDir, SHIPPED_LOCALES } from "../packages/contracts/src/i18n-node.ts";

const here = fileURLToPath(import.meta.url);
const root = join(here, "..", "..");
export const KEYS_FILE = "packages/contracts/src/i18n-keys.gen.ts";

export function keysSource(): string {
  const problems: string[] = [];
  const pack = readPackDir(join(SHIPPED_LOCALES, FALLBACK_LANG), problems);
  if (problems.length) throw new Error(problems.join("\n"));
  const lines = Object.keys(pack)
    .sort()
    .map((k) => {
      const ps = paramsOf(pack[k]!).filter((p) => !(p in BUILTIN_PARAMS));
      return `  ${JSON.stringify(k)}: ${ps.length ? ps.map((p) => JSON.stringify(p)).join(" | ") : "never"};`;
    });
  return [
    "// Generated by scripts/gen-i18n-keys.ts from packages/contracts/locales/en — do not edit.",
    "// After changing the packs: npm run gen:i18n (ADR-159).",
    "",
    "/** Every message key → the names of its params (`never`: none; `{product}` / `{command}` are always filled). */",
    "export interface MessageParams {",
    ...lines,
    "}",
    "export type MessageKey = keyof MessageParams;",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === here) {
  const text = keysSource();
  const file = join(root, KEYS_FILE);
  let old = "";
  try {
    old = readFileSync(file, "utf8");
  } catch {}
  if (old.replace(/\r\n/g, "\n") === text) process.exit(0);
  if (process.argv.includes("--check")) {
    console.error(`${KEYS_FILE} is stale: run npm run gen:i18n and commit it`);
    process.exit(1);
  }
  writeFileSync(file, text);
  console.log(`wrote ${KEYS_FILE}`);
}
